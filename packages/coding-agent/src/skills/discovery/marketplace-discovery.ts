/**
 * Searches the curated 75 skills catalog.
 */
export function searchCuratedSkills(query: string, options: { category?: string; repository?: string } = {}): SkillSearchResult[] {
	const normalizedQuery = query.toLowerCase().trim();
	const tokens = normalizedQuery.split(/\s+/).filter(Boolean);

	return CURATED_75_SKILLS.filter(entry => {
		if (options.category && entry.category !== options.category) {
			return false;
		}
		if (options.repository && entry.repository.toLowerCase() !== options.repository.toLowerCase()) {
			return false;
		}
		if (tokens.length === 0) {
			return true;
		}

		const searchable = `${entry.id} ${entry.name} ${entry.description} ${entry.utility} ${entry.repository} ${entry.tags.join(" ")}`.toLowerCase();
		return tokens.every(token => searchable.includes(token));
	}).map(entry => ({
		id: entry.id,
		name: entry.name,
		description: entry.description,
		utility: entry.utility,
		repository: entry.repository,
		category: entry.category,
		isInstalled: false,
		source: "curated",
		trust: "verified",
	}));
}

/**
 * Finds a specific curated skill by ID or by repository + subpath.
 */
export function findCuratedSkill(idOrName: string, repository?: string): CuratedSkillEntry | undefined {
	const normalized = idOrName.toLowerCase().trim();
	return CURATED_75_SKILLS.find(item => {
		if (repository && item.repository.toLowerCase() !== repository.toLowerCase()) {
			return false;
		}
		return item.id.toLowerCase() === normalized || item.name.toLowerCase() === normalized;
	});
}
